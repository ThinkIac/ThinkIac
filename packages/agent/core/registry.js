import { readFileSync, writeFileSync, existsSync, mkdirSync, unlinkSync } from 'fs'
import { join, dirname, resolve } from 'path'
import { fileURLToPath } from 'url'
import { runInSandbox }  from './sandbox.js'

const PKG_DIR    = dirname(fileURLToPath(import.meta.url))
const AGENT_DIR = resolve(PKG_DIR, '..')
const GEN        = join(AGENT_DIR, 'generated')
const IDX     = join(GEN, '_index.json')
const registry = new Map()

const ensureGen = () => { if (!existsSync(GEN)) mkdirSync(GEN, { recursive: true }) }
const readIdx   = () => { if (!existsSync(IDX)) return {}; try { return JSON.parse(readFileSync(IDX, 'utf8')) } catch { return {} } }
const writeIdx  = (d) => { ensureGen(); writeFileSync(IDX, JSON.stringify(d, null, 2), 'utf8') }
const toCamel   = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase())

export function registerTool(name, schema, fn, mode = 'sandbox', filePath = null) {
  registry.set(name, { schema, fn, mode, created_at: new Date().toISOString(), file: filePath })
}

export function persistTool(name, description, paramDefs, code) {
  ensureGen()
  const params = paramDefs.map(p => ` * @param {${p.type}${p.optional ? '?' : ''}} ${p.name} - ${p.description}`).join('\n')
  const src = `// Auto-generated by Agent — ${new Date().toISOString()}\n\nexport async function ${toCamel(name)}(input) {\n  /**\n   * @register_tool ${name}\n   * @description ${description}\n${params}\n   */\n  ${code}\n}\n`
  const fp = join(GEN, `${name}.js`)
  writeFileSync(fp, src, 'utf8')
  const idx = readIdx(); idx[name] = { description, paramDefs, file: fp, created_at: new Date().toISOString() }; writeIdx(idx)
  return fp
}

export function deleteTool(name) {
  const e = registry.get(name)
  if (e?.file && existsSync(e.file)) { unlinkSync(e.file); const idx = readIdx(); delete idx[name]; writeIdx(idx) }
  registry.delete(name)
}

export async function invokeTool(name, input = {}) {
  const e = registry.get(name)
  if (!e) throw new Error(`Tool "${name}" not found`)
  return await e.fn(input)
}

export const hasTool         = (name) => registry.has(name)
export const listToolSchemas = () => Array.from(registry.entries()).map(([name, e]) => ({
  name, description: e.schema.description, input_schema: e.schema.input_schema, mode: e.mode,
}))

export async function loadPersistedTools() {
  const idx = readIdx(); let loaded = 0
  for (const [name, meta] of Object.entries(idx)) {
    if (!existsSync(meta.file)) continue
    try {
      const raw   = readFileSync(meta.file, 'utf8')
      const match = raw.match(/\*\/\s*([\s\S]+?)\n}$/)
      const body  = match?.[1]?.trim() ?? ''
      const fn    = async (input) => { const r = await runInSandbox(body, input); if (!r.success) throw new Error(r.error); return r.output }
      registerTool(name, { description: meta.description, input_schema: buildSchema(meta.paramDefs ?? []) }, fn, 'permanent', meta.file)
      loaded++
    } catch (e) { console.warn(`[Agent] Could not reload "${name}":`, e.message) }
  }
  return loaded
}

export function buildSchema(paramDefs = []) {
  const properties = {}, required = []
  for (const p of paramDefs) {
    properties[p.name] = { type: p.type, description: p.description }
    if (!p.optional) required.push(p.name)
  }
  return { type: 'object', properties, required }
}
