const DEFAULT_GITHUB_OWNER = 'ThinkIac';
const GITHUB_API = 'https://api.github.com';
const NPM_REGISTRY = 'https://registry.npmjs.org';

function text(value, label) {
  const result = String(value || '').trim();
  if (!result) throw new Error(`${label} is required`);
  return result;
}

function namePart(value, label) {
  const result = text(value, label);
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(result)) throw new Error(`Invalid ${label}`);
  return result;
}

function host(value) {
  const result = text(value, 'host');
  // Bracketed IPv6 is accepted. Ports and protocols deliberately live in a
  // connection configuration, not in this portable package identifier.
  if (!/^(?:[A-Za-z0-9.-]+|\[[0-9A-Fa-f:.]+\])$/.test(result)) throw new Error('Invalid host');
  return result;
}

function validBranch(value) {
  return typeof value === 'string'
    && /^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(value)
    && !value.includes('..')
    && !value.endsWith('/')
    && !value.endsWith('.');
}

/** Parses the portable pkgmgr identifier without performing I/O. */
export function parsePackageIdentifier(identifier) {
  const input = text(identifier, 'package identifier');
  let match = /^(?:(git|npm)(?:@(\[[^\]]+\]|[^:]+))?:)?([^/]+)\/([^/]+)$/.exec(input);
  if (!match && !input.includes(':') && !input.includes('/')) {
    return { provider: 'git', host: 'github.com', owner: DEFAULT_GITHUB_OWNER, package: namePart(input, 'package name'), selfHosted: false };
  }
  if (!match) throw new Error('Invalid package identifier. Use name, git:owner/name, npm:scope/name, git@host:owner/name or npm@host:scope/name');
  const [, provider, customHost, owner, packageName] = match;
  if (!provider) throw new Error('A slash form must include a git: or npm: provider prefix');
  const resolvedHost = customHost ? host(customHost) : provider === 'git' ? 'github.com' : 'registry.npmjs.org';
  return {
    provider,
    host: resolvedHost,
    owner: namePart(owner, provider === 'npm' ? 'package scope' : 'repository owner'),
    package: namePart(packageName, 'package name'),
    selfHosted: Boolean(customHost),
  };
}

function githubHeaders() {
  return { Accept: 'application/vnd.github+json', 'User-Agent': 'thinkiac-pkgmgr' };
}

async function responseJson(fetchFn, url) {
  const response = await fetchFn(url, { headers: githubHeaders() });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`GitHub responded ${response.status}`);
  return response.json();
}

function releaseAsset(release) {
  return (release?.assets || []).find(asset => typeof asset?.name === 'string'
    && /^package-v[^/]+\.zip$/i.test(asset.name)
    && typeof asset.browser_download_url === 'string');
}

/** Lists branches that may be selected when a GitHub package has no release. */
export async function listGitHubBranches(identifier, { fetchFn = fetch } = {}) {
  const parsed = parsePackageIdentifier(identifier);
  if (parsed.provider !== 'git' || parsed.host !== 'github.com') {
    throw new Error('Branch listing is available only for GitHub package sources');
  }
  const repoPath = `${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.package)}`;
  const branches = await responseJson(fetchFn, `${GITHUB_API}/repos/${repoPath}/branches?per_page=100`);
  if (!branches) throw new Error(`GitHub repository ${parsed.owner}/${parsed.package} was not found`);
  if (!Array.isArray(branches)) throw new Error('GitHub returned an invalid branch list');
  return branches
    .map(branch => branch?.name)
    .filter(validBranch);
}

/**
 * Resolves an installable source. GitHub package releases generated by the
 * Engineer CI are preferred. A repository with no compatible release is not
 * an error: its default (or explicitly requested) branch is the fallback.
 */
export async function resolvePackageSource(identifier, { branch, fetchFn = fetch } = {}) {
  const parsed = parsePackageIdentifier(identifier);
  if (branch && !validBranch(branch)) throw new Error('Invalid branch name');

  if (parsed.provider === 'npm') {
    const registry = parsed.host === 'registry.npmjs.org' ? NPM_REGISTRY : `https://${parsed.host}`;
    return { ...parsed, kind: 'npm', registry, packageName: `@${parsed.owner}/${parsed.package}` };
  }

  const cloneUrl = `https://${parsed.host}/${parsed.owner}/${parsed.package}.git`;
  if (parsed.host !== 'github.com') return { ...parsed, kind: 'git', cloneUrl, branch: branch || null, release: null };

  const repoPath = `${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.package)}`;
  if (!branch) {
    const latest = await responseJson(fetchFn, `${GITHUB_API}/repos/${repoPath}/releases/latest`);
    const asset = releaseAsset(latest);
    if (asset) {
      return { ...parsed, kind: 'release-zip', cloneUrl, branch: null, release: { tag: latest.tag_name, asset: asset.name, url: asset.browser_download_url } };
    }
  }
  const repository = await responseJson(fetchFn, `${GITHUB_API}/repos/${repoPath}`);
  if (!repository) throw new Error(`GitHub repository ${parsed.owner}/${parsed.package} was not found`);
  return { ...parsed, kind: 'git', cloneUrl, branch: branch || repository.default_branch || null, release: null };
}
